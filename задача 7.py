# Считываем данные: рубли (A), копейки (B) и количество пирожков (N)
a = int(input())
b = int(input())
n = int(input())

# 1. Считаем стоимость одного пирожка в копейках
price_in_kopeks = a * 100 + b

# 2. Считаем общую стоимость всех N пирожков в копейках
total_kopeks = price_in_kopeks * n

# 3. Переводим общую сумму обратно в рубли и копейки
# Рубли — это целая часть от деления на 100
total_rub = total_kopeks // 100
# Копейки — это остаток от деления на 100
total_kop = total_kopeks % 100

# Выводим два числа через пробел
print(total_rub, total_kop)
# Получаем входные данные от пользователя
# input() считывает строку с клавиатуры
N = input("Введите число: ")

# Преобразуем строку в целое число
# int() превращает строку в число для математических операций
number = int(N)

# Находим первую цифру числа математическим способом
# Берём абсолютное значение, чтобы正确处理 отрицательные числа
temp = abs(number)

# Пока число больше или равно 10, отбрасываем последнюю цифру
while temp >= 10:
    # Целочисленное деление на 10 отбрасывает последнюю цифру
    # Например: 753 // 10 = 75, затем 75 // 10 = 7
    temp = temp // 10

# Теперь temp содержит первую цифру исходного числа
first_digit = temp

# Выводим результат на экран
print(f"Первая цифра числа {number}: {first_digit}")
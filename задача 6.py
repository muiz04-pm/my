# Считываем количество учеников в каждом из трех классов
class1 = int(input())
class2 = int(input())
class3 = int(input())

# Считаем парты для каждого класса отдельно.
# Формула (n + 1) // 2 автоматически округляет результат деления на 2 в большую сторону.
desks1 = (class1 + 1) // 2
desks2 = (class2 + 1) // 2
desks3 = (class3 + 1) // 2

# Складываем результаты и выводим общую сумму парт
print(desks1 + desks2 + desks3)
